negative = ""

existing = set()
if os.path.exists(out_dir):
    for f in os.listdir(out_dir):
        if f.endswith(".png") and f.startswith("landscape_"):
            existing.add(f)

start = len(existing)
total = 100

for i in range(start, total):
    p = prompts[i % len(prompts)]
    full = f"{p}，{base}"
    print(f"[{i+1}/{total}] Generating... {p[:20]}...")
    image = pipe(
        prompt=full,
        negative_prompt=negative,
        height=1280,
        width=960,
        cfg_normalization=False,
        num_inference_steps=50,
        guidance_scale=5,
        generator=torch.Generator("cuda").manual_seed(42 + i),
    ).images[0]
    path = os.path.join(out_dir, f"landscape_{i+1:03d}.png")
    image.save(path)
    print(f"  -> landscape_{i+1:03d}.png saved")
